"""Train the bigram and MLP name models, compare them, save charts and export the MLP for the web app.

    python training/train.py
"""
import json
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from model import CHARS, MLP, Bigram, make_dataset

ROOT = Path(__file__).resolve().parent.parent
BLOCK, STEPS, BATCH = 3, 100000, 64


def sample(prob_fn, n, rng, temperature=1.0, max_len=20):
    out = []
    for _ in range(n):
        ctx, name = [0] * BLOCK, ""
        while len(name) < max_len:
            p = prob_fn(np.array([ctx]))[0]
            p = p ** (1 / temperature); p /= p.sum()
            ix = rng.choice(len(p), p=p)
            if ix == 0:
                break
            name += CHARS[ix]; ctx = ctx[1:] + [ix]
        out.append(name)
    return out


def main():
    names = sorted(set(open(ROOT / "data" / "names.txt").read().split()))      # dedupe: no name in two splits
    rng = np.random.default_rng(42); rng.shuffle(names)
    n1, n2 = int(0.8 * len(names)), int(0.9 * len(names))
    train, val, test = names[:n1], names[n1:n2], names[n2:]
    Xtr, Ytr = make_dataset(train, BLOCK); Xva, Yva = make_dataset(val, BLOCK); Xte, Yte = make_dataset(test, BLOCK)
    print(f"{len(names):,} unique names -> train {len(train):,} / val {len(val):,} / test {len(test):,}  ({len(Xtr):,} training examples)")

    uniform = float(np.log(len(CHARS)))
    bigram = Bigram().fit(train)
    print(f"uniform guessing loss {uniform:.3f} | bigram val loss {bigram.loss(Xva, Yva):.3f}")

    mlp = MLP(block=BLOCK)
    n_params = sum(p.size for p in mlp.params().values())
    hist = {"step": [], "train": [], "val": []}
    t0 = time.time()
    for step in range(STEPS + 1):
        if step % 1000 == 0:
            idx = rng.integers(0, len(Xtr), 20000)
            hist["step"].append(step); hist["train"].append(mlp.loss(Xtr[idx], Ytr[idx])); hist["val"].append(mlp.loss(Xva, Yva))
            if step % 20000 == 0:
                print(f"step {step:6d}  train {hist['train'][-1]:.3f}  val {hist['val'][-1]:.3f}")
        if step == STEPS:
            break
        idx = rng.integers(0, len(Xtr), BATCH)                # mini-batch gradient descent
        mlp.loss(Xtr[idx], Ytr[idx])
        lr = 0.1 if step < 75000 else 0.01                    # learning-rate decay for the final stretch
        mlp.step(mlp.backward(Ytr[idx]), lr)
    print(f"trained {n_params:,} parameters in {time.time() - t0:.0f}s")

    res = {"uniform": uniform, "bigram_test": bigram.loss(Xte, Yte), "mlp_test": mlp.loss(Xte, Yte),
           "mlp_train": mlp.loss(Xtr, Ytr), "params": int(n_params)}
    for k in ("bigram_test", "mlp_test"):
        res[k.replace("test", "perplexity")] = float(np.exp(res[k]))
    print(f"TEST loss: bigram {res['bigram_test']:.3f} (perplexity {res['bigram_perplexity']:.1f}) | "
          f"MLP {res['mlp_test']:.3f} (perplexity {res['mlp_perplexity']:.1f}) | MLP train {res['mlp_train']:.3f}")

    # ---------- samples: how many are new inventions vs copies of training names ----------
    srng = np.random.default_rng(7)
    train_set, all_set = set(train), set(names)
    samples = {"bigram": sample(lambda X: bigram.P[X[:, -1]], 500, srng), "mlp": sample(mlp.forward, 500, srng)}
    for m, s in samples.items():
        real = np.mean([x in all_set for x in s]); novel = np.mean([x not in train_set for x in s])
        res[f"{m}_real_rate"] = float(real); res[f"{m}_novel_rate"] = float(novel)
        print(f"{m:6s} samples: {real:.0%} are real names in the dataset, {novel:.0%} not in training set | e.g. {', '.join(s[:10])}")

    # ---------- export ----------
    export = mlp.export() | {"chars": CHARS, "test_loss": round(res["mlp_test"], 4), "bigram_test_loss": round(res["bigram_test"], 4),
                             "bigram": np.round(bigram.P, 6).tolist()}
    (ROOT / "web" / "model.js").write_text("// Auto-generated by training/train.py\nconst MODEL = " + json.dumps(export) + ";\n")
    (ROOT / "web" / "names.js").write_text("// Every name in the dataset, to tell real names from new inventions\nconst NAMES = new Set(" +
                                           json.dumps(sorted(names)) + ");\n")
    ctxs = [[0, 0, 0], [0, 0, 13], [1, 25, 1], [11, 9, 1]]                  # fixtures for the JS parity test
    json.dump({"contexts": ctxs, "probs": mlp.forward(np.array(ctxs)).round(8).tolist()}, open(ROOT / "web" / "test_fixtures.json", "w"))
    json.dump(res | {"history": hist, "samples": {k: v[:50] for k, v in samples.items()}}, open(ROOT / "training" / "results.json", "w"), indent=1)

    # ---------- charts ----------
    plt.style.use("seaborn-v0_8-whitegrid")
    fig, ax = plt.subplots(figsize=(10, 4.2))
    ax.plot(hist["step"], hist["train"], color="#94a3b8", lw=2, label="MLP training loss")
    ax.plot(hist["step"], hist["val"], color="#7c3aed", lw=2.5, label="MLP validation loss")
    ax.axhline(bigram.loss(Xva, Yva), color="#f97316", ls="--", lw=2, label=f"bigram baseline ({bigram.loss(Xva, Yva):.2f})")
    ax.axhline(uniform, color="#ef4444", ls=":", lw=1.5, label=f"random guessing ({uniform:.2f})")
    ax.axvline(75000, color="#cbd5e1", lw=1); ax.text(75800, 2.62, "learning rate\n0.1 → 0.01", fontsize=8, color="#64748b")
    ax.set(title=f"Training a {n_params:,}-parameter neural language model", xlabel="training step (batch of 64)",
           ylabel="cross-entropy loss (lower = better)", ylim=(1.9, 3.45))
    ax.legend(loc="center right", bbox_to_anchor=(1, 0.68)); fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "training_loss.png", dpi=130)

    E = mlp.C - mlp.C.mean(0)
    U, S, Vt = np.linalg.svd(E, full_matrices=False)
    xy = E @ Vt[:2].T
    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    span = xy.max(0) - xy.min(0)
    ax.set_xlim(xy[:, 0].min() - 0.1 * span[0], xy[:, 0].max() + 0.1 * span[0])   # text doesn't resize axes, so set limits
    ax.set_ylim(xy[:, 1].min() - 0.1 * span[1], xy[:, 1].max() + 0.1 * span[1])
    for i, c in enumerate(CHARS):
        col = "#dc2626" if c in "aeiouy" else "#0f172a" if c != "." else "#16a34a"
        if c == ".":                                   # the end-of-name token: label it off to the side so it isn't hidden
            ax.scatter(*xy[i], s=30, color=col, alpha=.5, zorder=1)
            ax.annotate("END of name", xy[i], xytext=(xy[i][0] - 0.28 * span[0], xy[i][1] + 0.16 * span[1]),
                        color=col, fontsize=11, weight="bold", arrowprops=dict(arrowstyle="->", color=col))
            continue
        ax.text(*xy[i], c, ha="center", va="center", fontsize=15, color=col, weight="bold", zorder=3)
    ax.set(title="What the model learned: letter embeddings (2-D projection)\nred = vowels · black = consonants · green = end-of-name",
           xticks=[], yticks=[])
    fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "letter_embeddings.png", dpi=130)

    fig, ax = plt.subplots(figsize=(8, 3.6))
    labels = ["random\nguessing", "bigram\n(counting)", "neural MLP\n(this project)"]
    vals = [uniform, res["bigram_test"], res["mlp_test"]]
    bars = ax.bar(labels, vals, color=["#ef4444", "#f97316", "#7c3aed"])
    ax.bar_label(bars, labels=[f"{v:.3f}\n(perplexity {np.exp(v):.1f})" for v in vals], fontsize=9)
    ax.set(title="Test-set loss on 2,950 names no model has seen", ylabel="loss (lower = better)", ylim=(0, 4))
    fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "model_comparison.png", dpi=130)
    print("Saved charts to screenshots/ and model to web/model.js")


if __name__ == "__main__":
    main()
